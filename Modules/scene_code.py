import time
import threading
import collections

class SceneStoppedException(Exception):
    pass

class Scene:

    dmx = None
    fixture_matrix = None
    master_level = 255
    fader_callbacks = {}
    active_scene_threads = collections.defaultdict(dict)
    faders_direct = [0] * 16
    faders_scenes = [0] * 16
    lock = threading.Lock()
    _thread_local = threading.local()

    @classmethod
    def setup(cls, _dmx, _fixture_matrix, num_of_faders):
        """Init function for references on main DMX bus and fixture matrix."""
        cls.dmx = _dmx
        cls.fixture_matrix = _fixture_matrix
        for i in range(num_of_faders):
            cls.fader_callbacks[i+1] = []


    @classmethod
    def custom_sleep(cls, seconds):
        stop = getattr(cls._thread_local, "stop_event", None)
        if stop:
            if stop.is_set() or stop.wait(seconds):
                raise SceneStoppedException()

        else:
            time.sleep(seconds)


    @classmethod
    def set_fixture(cls, fix_num: int, attr_name: str, value: int, universe: int = 1):
        if not cls.fixture_matrix or not cls.dmx:
            return

        fix = cls.fixture_matrix.find_by_num(fix_num)
        if fix:
            dmx_addr = fix.get_channel_addr(attr_name)
            cls.dmx.set_channel(universe, dmx_addr, value)

    @classmethod
    def update_scene_faders(cls, channel: int, value: int):
        cls.faders_scenes[channel - 1] = value
        callback = cls.fader_callbacks.get(channel)
        to_join = None

        with cls.lock:
            entry = cls.active_scene_threads.get(channel)

            if value > 1:
                if callback and (entry is None or not entry["thread"].is_alive()):
                    stop = threading.Event()

                    def run_callback():
                        Scene._thread_local.stop_event = stop
                        try:
                            while not stop.is_set():
                                callback(cls.faders_scenes[channel - 1])  # current value
                                stop.wait(0.01)

                        except SceneStoppedException:
                            print("WARN: SceneStopException raised")

                        except Exception as e:
                            print(f"Error in scene callback channel {channel}: {e}")

                        finally:
                            if hasattr(Scene._thread_local, "stop_event"):
                                delattr(Scene._thread_local, "stop_event")

                    thread = threading.Thread(target=run_callback, daemon=True)
                    cls.active_scene_threads[channel] = {"thread": thread, "stop": stop}
                    thread.start()
                    print("INFO: Started scene on fader: ", channel)
            
            elif entry:
                entry["stop"].set()
                cls.active_scene_threads.pop(channel)
                to_join = entry["thread"]
                print("INFO: Stopped scene on fader: ", channel)

        if to_join and to_join is not threading.current_thread():
            to_join.join(timeout=0.5)

    
    @classmethod
    def register_fader_callback(cls, fader_num: int, callback):
        cls.fader_callbacks[int(fader_num)] = callback


    @classmethod
    def update_dmx_faders(cls, channel: int, value: int):
        cls.faders_direct[channel-1] = value


    @classmethod
    def get_dmx_channels(cls):
        return cls.faders_direct


    @classmethod
    def get_scene_channels(cls):
        return cls.faders_scenes


    @classmethod
    def execute(cls, code_string: str, master_level: int = 255):
        """Executes given code generated by blockly."""

        context = {
            "set_fixture": cls.set_fixture,
            "wait": time.sleep
        }

        thread = threading.Thread(target=exec, args=(code_string, context), daemon=True)
        thread.start()
        return thread